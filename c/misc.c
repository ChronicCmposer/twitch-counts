/* complete_channels: sorted(alias keys + logs-root subdirs). */
static void misc_complete_channels(misc_state *st) {
    toml_table_t *aliases;
    int total;
    int i;

    if (st->config != NULL) {
        aliases = toml_table_in(st->config, "aliases");
        if (aliases != NULL) {
            total = toml_table_nkval(aliases) + toml_table_narr(aliases)
                + toml_table_ntab(aliases);
            for (i = 0; i < total; i++) {
                const char *key = toml_key_in(aliases, i);
                if (key != NULL) {
                    misc_names_add(&st->names, key);
                }
            }
        }
    }
    /* logs-root subdirectories (Python: if os.path.isdir(logs_root)) */
    misc_expand_root(st);
    if (misc_is_dir(st->logs_root)) {
        misc_list_dirs(st->logs_root, &st->names);
    }
    misc_names_sort(&st->names);
    misc_names_print(&st->names);
}

/* complete_groups: sorted [exclude] group names (config_exclusions). */
static void misc_complete_groups(misc_state *st) {
    if (misc_cfg_exclusions(st) != 0) {
        return;   /* error printed */
    }
    misc_names_sort(&st->excl.groups);
    misc_names_print(&st->excl.groups);
}

/* complete_dates: every dated log file's date, ascending, one per line. */
static void misc_complete_dates(misc_state *st) {
    misc_log_entry *entries = NULL;
    size_t count = 0;
    size_t i;
    char buf[16];

    if (misc_listing_build(st, &entries, &count) != 0) {
        free(entries);
        return;
    }
    for (i = 0; i < count; i++) {
        misc_fmt_ymd(entries[i].ymd, buf);
        tc_puts(buf);
        tc_puts("\n");
    }
    free(entries);
}

/* complete_weeks: ISO weeks of the dated logs, deduped, in date order
   (sorting the dedup list is a no-op for well-formed ISO weeks — the asm
   port sorts; the Python relies on the date order). */
static void misc_complete_weeks(misc_state *st) {
    misc_log_entry *entries = NULL;
    size_t count = 0;
    size_t i;
    char buf[16];

    if (misc_listing_build(st, &entries, &count) != 0) {
        free(entries);
        return;
    }
    for (i = 0; i < count; i++) {
        int year, week;
        misc_iso_week(entries[i].ymd, &year, &week);
        misc_fmt_week(year, week, buf);
        misc_names_add(&st->names, buf);
    }
    free(entries);
    misc_names_sort(&st->names);
    misc_names_print(&st->names);
}

/* complete_periods: weeks then dates (Python: weeks + dates). */
static void misc_complete_periods(misc_state *st) {
    misc_log_entry *entries = NULL;
    size_t count = 0;
    size_t i;
    char buf[16];

    if (misc_listing_build(st, &entries, &count) != 0) {
        free(entries);
        return;
    }
    for (i = 0; i < count; i++) {
        int year, week;
        misc_iso_week(entries[i].ymd, &year, &week);
        misc_fmt_week(year, week, buf);
        misc_names_add(&st->names, buf);
    }
    misc_names_print(&st->names);   /* weeks: date order, not re-sorted */
    for (i = 0; i < count; i++) {
        misc_fmt_ymd(entries[i].ymd, buf);
        tc_puts(buf);
        tc_puts("\n");
    }
    free(entries);
}

/* Stable sort descending by value, ties keeping the input order (Python
   Counter.most_common: count desc, first-seen ties). */
static void misc_sort_by_value(int64_t *idx, int64_t *vals, int64_t n) {
    int64_t i, j;
    if (n < 2) {
        return;
    }
    for (i = 1; i < n; i++) {
        int64_t key_idx = idx[i];
        int64_t key_val = vals[i];
        j = i - 1;
        while (j >= 0 && vals[j] < key_val) {
            idx[j + 1] = idx[j];
            vals[j + 1] = vals[j];
            j--;
        }
        idx[j + 1] = key_idx;
        vals[j + 1] = key_val;
    }
}

static int misc_in_users(const tc_users *users, const char *login) {
    int64_t i;
    for (i = 0; i < users->count; i++) {
        if (strcmp(users->entries[i].login, login) == 0) {
            return 1;
        }
    }
    return 0;
}

/* complete_users: a 7-day counting pass, then sorted config-known.  The
   window is end = now UTC, begin = end - 7 days (documented divergence: the
   Python uses local time). */
static void misc_complete_users(misc_state *st) {
    tc_window window;
    tc_users users;
    tc_tally tally;
    tc_opts copy;
    int64_t end_ymd, end_sod;
    int64_t begin_ymd, begin_sod;
    int64_t end_epoch;
    int64_t *idx = NULL;
    int64_t *vals = NULL;
    int64_t n;
    int64_t i;
    size_t g, j;

    /* the Python's config_exclusions runs inside complete_users — validate
       the [exclude] shape quietly before the count */
    if (misc_cfg_exclusions(st) != 0) {
        return;   /* error printed */
    }

    tc_misc_now_utc(&end_ymd, &end_sod);
    end_epoch = tc_ymd_sod_to_epoch(end_ymd, end_sod);
    tc_epoch_to_ymd_sod(end_epoch - 7 * TC_SECS_PER_DAY, &begin_ymd,
                        &begin_sod);
    memset(&window, 0, sizeof(window));
    window.begin_ymd = begin_ymd;
    window.begin_sod = begin_sod;
    window.end_ymd = end_ymd;
    window.end_sod = end_sod;
    window.kind = TC_WIN_BEGIN;
    window.threshold = 1;
    window.state_filter = TC_ST_NONE;

    /* The Python counts EVERYONE (no exclusion filtering) and never
       validates --exclude-group / --no-exclude for the users kind, so the
       counting pass gets a sanitized copy: exclusions neutralized and the
       channel/logs-root resolved (the alias was already applied). */
    copy = *st->opts;
    copy.flags |= TC_F_NO_EXCLUDE;
    copy.flags &= ~(TC_F_EXCL_GIVEN | TC_F_EXCL_GROUP_GIVEN
                    | TC_F_EXCLUDE_BCAST | TC_F_INCL_GIVEN);
    copy.excl_count = 0;
    copy.excl_group_count = 0;
    copy.incl_count = 0;
    copy.excl_bcast_val = 0;
    tc_copy_str_cap(copy.channel, st->channel_name, sizeof(copy.channel));
    tc_copy_str_cap(copy.logs_dir, st->logs_root, sizeof(copy.logs_dir));

    memset(&users, 0, sizeof(users));
    memset(&tally, 0, sizeof(tally));
    tally.users = &users;
    if (tc_count_run(&copy, &window, &tally) != TC_EXIT_OK) {
        /* tc_build_exclusions cannot fail on the sanitized copy and the
           channel was already resolved, so this is unreachable. */
        free(users.entries);
        return;
    }

    /* most_common() order: stable sort of (index, total) by total desc */
    n = users.count;
    if (n > 0) {
        idx = malloc((size_t)n * sizeof(int64_t));
        vals = malloc((size_t)n * sizeof(int64_t));
        if (idx == NULL || vals == NULL) {
            tc_fail("out of memory");
        }
    }
    for (i = 0; i < n; i++) {
        idx[i] = i;
        vals[i] = tc_user_count(&users.entries[i]);
    }
    misc_sort_by_value(idx, vals, n);
    for (i = 0; i < n; i++) {
        tc_puts(users.entries[idx[i]].login);
        tc_puts("\n");
    }
    free(idx);
    free(vals);

    /* sorted(known - counts): flat exclusions + every group's members */
    {
        misc_names known;
        misc_names_init(&known);
        for (j = 0; j < st->excl.flat.count; j++) {
            misc_names_add(&known, st->excl.flat.items[j]);
        }
        for (g = 0; g < st->excl.group_count; g++) {
            const misc_group *gr = &st->excl.group_recs[g];
            for (j = 0; j < gr->members.count; j++) {
                misc_names_add(&known, gr->members.items[j]);
            }
        }
        misc_names_sort(&known);
        for (j = 0; j < known.count; j++) {
            if (misc_in_users(&users, known.items[j])) {
                continue;
            }
            tc_puts(known.items[j]);
            tc_puts("\n");
        }
        misc_names_free(&known);
    }

    free(users.entries);
    free(tc_core_listing.entries);
    tc_core_listing.entries = NULL;
    tc_core_listing.count = 0;
    tc_core_listing.cap = 0;
}

/* Add every member of the named group to st->names; 0 found, 1 unknown. */
static int misc_add_group_members(misc_state *st, const char *name) {
    int gi = misc_group_index(st, name);
    size_t j;
    if (gi < 0) {
        return 1;
    }
    for (j = 0; j < st->excl.group_recs[gi].members.count; j++) {
        misc_names_add(&st->names, st->excl.group_recs[gi].members.items[j]);
    }
    return 0;
}

/* Python resolve("exclude-broadcaster", ...) + convert(parse_bool): CLI
   wins, then env TWITCH_EXCLUDE_BROADCASTER, then config
   exclude_broadcaster, else False.  Returns 1 yes / 0 no / -1 error printed. */
static int misc_wants_broadcaster(misc_state *st) {
    const tc_opts *opts = st->opts;
    const char *env;
    int ok = 1;
    int value;
    char *m;
    char *end;

    if (opts->flags & TC_F_EXCLUDE_BCAST) {
        return opts->excl_bcast_val != 0;
    }
    env = getenv("TWITCH_EXCLUDE_BROADCASTER");
    if (env != NULL && env[0] != '\0') {
        value = tc_parse_bool(env, &ok);
        if (!ok) {
            m = st->msg;
            end = st->msg + sizeof(st->msg);
            m = misc_cat(m, end, "--exclude-broadcaster (from env "
                                 "TWITCH_EXCLUDE_BROADCASTER): expected true "
                                 "or false, got ");
            m = misc_py_repr(m, (size_t)(end - m), env);
            m = st->msg + strlen(st->msg);
            *m = '\0';
            misc_failed(st, st->msg);
            return -1;
        }
        return value;
    }
    if (st->config != NULL) {
        const char *raw = toml_raw_in(st->config, "exclude_broadcaster");
        if (raw != NULL) {
            char val[MISC_VALUE_SZ];
            misc_toml_value_to_string(raw, val, sizeof(val));
            value = tc_parse_bool(val, &ok);
            if (!ok) {
                m = st->msg;
                end = st->msg + sizeof(st->msg);
                m = misc_cat(m, end, "--exclude-broadcaster (from config): "
                                     "expected true or false, got ");
                m = misc_py_repr(m, (size_t)(end - m), val);
                m = st->msg + strlen(st->msg);
                *m = '\0';
                misc_failed(st, st->msg);
                return -1;
            }
            return value;
        }
    }
    return 0;
}

/* complete_includes: sorted merged exclusion logins (Python build_exclusions
   + exclusion_layers + the --include subtraction). */
static void misc_complete_includes(misc_state *st) {
    const tc_opts *opts = st->opts;
    const char *conf[4];
    int n = 0;
    int i;
    int wb;
    char *m;
    char *end;

    /* Python build_exclusions checks --no-exclude conflicts FIRST */
    if (opts->flags & TC_F_NO_EXCLUDE) {
        if (opts->flags & TC_F_EXCL_GIVEN) {
            conf[n++] = "--exclude";
        }
        if (opts->flags & TC_F_EXCL_GROUP_GIVEN) {
            conf[n++] = "--exclude-group";
        }
        if (opts->flags & TC_F_EXCLUDE_BCAST) {
            conf[n++] = "--exclude-broadcaster";
        }
        if (opts->flags & TC_F_INCL_GIVEN) {
            conf[n++] = "--include";
        }
        if (n > 0) {
            m = st->msg;
            end = st->msg + sizeof(st->msg);
            m = misc_cat(m, end, "--no-exclude cannot be combined with ");
            for (i = 0; i < n; i++) {
                if (i > 0) {
                    m = misc_cat(m, end, ", ");
                }
                m = misc_cat(m, end, conf[i]);
            }
            *m = '\0';
            misc_failed(st, st->msg);
            return;
        }
        return;   /* --no-exclude with nothing conflicting: empty candidates */
    }

    /* config exclusions (quiet) */
    if (misc_cfg_exclusions(st) != 0) {
        return;
    }
    /* layer 1: config flat */
    for (i = 0; i < (int)st->excl.flat.count; i++) {
        misc_names_add(&st->names, st->excl.flat.items[i]);
    }
    /* layer 2: config always:<name> groups (unknown always names were
       rejected by config_exclusions above) */
    for (i = 0; i < (int)st->excl.always.count; i++) {
        misc_add_group_members(st, st->excl.always.items[i]);
    }
    /* layer 3: --exclude-group NAME (validated like the Python) */
    for (i = 0; i < opts->excl_group_count; i++) {
        if (misc_add_group_members(st, opts->excl_group_list[i]) == 0) {
            continue;
        }
        m = st->msg;
        end = st->msg + sizeof(st->msg);
        m = misc_cat(m, end, "unknown exclude group ");
        m = misc_py_repr(m, (size_t)(end - m), opts->excl_group_list[i]);
        m = st->msg + strlen(st->msg);
        m = misc_cat(m, end, "; defined groups: ");
        m = misc_cat_sorted_groups(st, m, end);
        *m = '\0';
        misc_failed(st, st->msg);
        return;
    }
    /* layer 4: env TWITCH_EXCLUDE */
    {
        const char *env = getenv("TWITCH_EXCLUDE");
        if (env != NULL && env[0] != '\0') {
            misc_split_add(&st->names, env);
        }
    }
    /* layer 5: --exclude LOGIN[,LOGIN...] */
    for (i = 0; i < opts->excl_count; i++) {
        misc_split_add(&st->names, opts->excl_list[i]);
    }
    /* layer 6: --exclude-broadcaster (login = lowercased channel) */
    wb = misc_wants_broadcaster(st);
    if (wb < 0) {
        return;   /* error printed */
    }
    if (wb) {
        char lower[TC_CHANNEL_SZ];
        misc_lowercase_into(st->channel_name, lower, sizeof(lower));
        misc_names_add(&st->names, lower);
    }
    /* --include subtraction */
    for (i = 0; i < opts->incl_count; i++) {
        misc_split_remove(&st->names, opts->incl_list[i]);
    }
    misc_names_sort(&st->names);
    misc_names_print(&st->names);
}

static void misc_state_free(misc_state *st) {
    if (st->config != NULL) {
        toml_free(st->config);
        st->config = NULL;
    }
    misc_names_free(&st->names);
    misc_excl_free(&st->excl);
}

