// ============================================================================
// misc.c — --manual / --emit-fish-completions / --complete.
//
//  The C sibling of asm/tc_misc.S: the --manual body, the fish completions
//  and the --complete candidate helper.  Behavioural oracle: twitch-counts.py
//  main() (manual/fish short-circuit) and completion_candidates +
//  run_completion, byte-for-byte wherever the Python's output is observable.
//
//  What this module owns
//  ---------------------
//    * --manual: print the module docstring with the {{ENVIRONMENT}} marker
//      replaced by environment_manual() plus print()'s newline.  The exact
//      bytes live in c/tc_manual.inc (generated by gen-tc-c-inc.sh).
//    * --emit-fish-completions: fish_completions(command="twitch-counts") plus
//      print()'s newline; exact bytes in c/tc_fish.inc, split in two where
//      fish_completions() embeds shorten_path(DEFAULT_CONFIG_PATH)
//      (twitch-counts.py:3954).  This module writes part A, the default
//      config path it computes the same way the Python does, then part B
//      (mirrors tc_misc_fish in the assembly port).
//    * --complete KIND: run_completion() — candidates for channels, groups,
//      dates, weeks, periods, users, includes, one per line.  A failure
//      prints  completion failed: ConfigError('...')  to stderr and returns
//      0, never a loud exit, exactly like the Python.
//
//  Completion pipeline (mirrors Python completion_candidates + run_completion)
//  ---------------------------------------------------------------------------
//    tc_misc_complete(opts):
//      1. config layer  (load_config_layer)  — a config that fails to LOAD
//         exits 1 loudly (the documented divergence); a missing default path
//         is an empty config.
//      2. channels/groups need no channel; the rest resolve the channel:
//         empty channel -> no output; missing logs root / channel dir ->
//         ConfigError report; the resolved dir drives the remaining kinds.
//      3. dates/weeks/periods: a dated-log listing built here with core.c's
//         tc_parse_log_filename_n (the shared FILENAME_RE filter, date
//         validation and sort), so the parse is the already-tested one.
//      4. users: tc_count_run with a synthetic window (end = now UTC, begin =
//         end - 7d), then most_common() order, then sorted(known - counts).
//      5. includes: the merged exclusion layers (Python build_exclusions)
//         computed here, so its errors stay quiet like run_completion.
//
//  Why the config/channel/exclusions are handled here rather than through
//  config.c/core.c: the config.c hooks only see a --config path once
//  s_opts is registered (after tc_cli_parse's settings resolution), and the
//  core/channel/exclusion paths fail loudly (exit 1) on a bad config or a
//  missing channel — but completion must never fail loudly at a prompt, so
//  the Python catches ConfigError/OSError in run_completion and reports it
//  on stderr with exit 0.  The shared parse helpers (tc_parse_log_filename_n,
//  tc_ascii_casecmp, the calendar arithmetic, tc_count_run) stay reused.
//
//  Deviation notes (shared with the asm port)
//  ------------------------------------------
//    * complete_users uses UTC "now" (the Python uses local time); the
//      differential generates logs that cover any 7-day window.
//    * A config that fails to LOAD (missing explicit path, TOML or I/O error)
//      exits 1 loudly — the documented divergence, shared with the asm port's
//      eager load (the Python reports quietly and exits 0).  Errors AFTER a
//      successful load ([exclude] shape, channel resolution) stay quiet.
//    * Config TOML errors use tomlc99's message ("line N: ...") instead of
//      tomllib's; the "could not read config <path>: " prefix is identical.
//    * The completion module parses the config itself with tomlc99 (it is
//      the first module to see a --config path), so a config that LOADS but
//      fails its [exclude] shape cannot exit 1 at a prompt (run_completion
//      catches and reports).
//    * Environment lookups use libc getenv() directly (never tc_env_get,
//      which would load the config and could tc_fail on a broken file).
//    * tc_count_run's entering-state seed scans files before the window
//      (the Python's complete_users starts the window in "unknown"); the
//      differential logs sit inside the window, so the candidates match.
// ============================================================================

