// ----------------------------------------------------------------------------
// Constants — mirrors the asm module (tc_misc.S).
// ----------------------------------------------------------------------------
enum {
    MISC_PATH_SZ     = 2048,   /* path buffers: logs root, channel dir, config */
    MISC_MSG_SZ      = 4096,   /* error-message composition buffer */
    MISC_ESC_SZ      = 8192,   /* escaped stderr report buffer */
    MISC_ERRBUF_SZ   = 128,    /* toml_parse_file error buffer */
    MISC_VALUE_SZ    = 512,    /* one TOML value / split token scratch */
    MISC_GROUPS_MAX  = 64,     /* [exclude] group cap (config.c's EX_GROUP_MAX) */
    MISC_LISTING_INIT = 64     /* dated-log listing initial capacity */
};

// ----------------------------------------------------------------------------
// Name list — a deduped, sortable, printable list of NUL-terminated strings
// (the asm port's misc_names arena, as a growing array).
// ----------------------------------------------------------------------------
typedef struct misc_names {
    char **items;
    size_t count;
    size_t cap;
} misc_names;

// ----------------------------------------------------------------------------
// Parsed [exclude] table (Python config_exclusions): groups, always-listed
// group names, and the flat login list.
// ----------------------------------------------------------------------------
typedef struct misc_group {
    char *name;                /* the config key, as written (not lowercased) */
    misc_names members;        /* lowercased member logins */
} misc_group;

typedef struct misc_excl {
    misc_names groups;         /* group names (complete_groups output) */
    misc_group group_recs[MISC_GROUPS_MAX];
    size_t group_count;
    misc_names always;         /* always-listed group names (raw) */
    misc_names flat;           /* flat logins (lowercased) */
} misc_excl;

// ----------------------------------------------------------------------------
// One dated log entry (Python log_files): the parsed date plus the filename,
// so the sort is (date, name) exactly like the Python's.
// ----------------------------------------------------------------------------
typedef struct misc_log_entry {
    int64_t ymd;
    char name[64];
} misc_log_entry;

// ----------------------------------------------------------------------------
// Module session — passed explicitly through the completion helpers (the C
// port keeps no hidden mutable globals).
// ----------------------------------------------------------------------------
typedef struct misc_state {
    const tc_opts *opts;
    toml_table_t *config;              /* parsed config table, or NULL */
    char config_path[MISC_PATH_SZ];    /* expanded config path */
    char config_where[MISC_PATH_SZ];   /* shorten_path(config_path) */
    char logs_root[MISC_PATH_SZ];      /* expanded logs root ("None" when empty) */
    char channel_dir[MISC_PATH_SZ];    /* <logs_root>/<channel dir name> */
    char channel_name[TC_CHANNEL_SZ];
    misc_names names;                  /* the candidate output list */
    misc_excl excl;
    char msg[MISC_MSG_SZ];             /* error-message composition scratch */
    char esc[MISC_ESC_SZ];             /* escaped stderr report buffer */
} misc_state;

// ----------------------------------------------------------------------------
// Small shared helpers.
// ----------------------------------------------------------------------------
static int misc_is_ws(unsigned char c) {
    return c == ' ' || c == '\t' || c == '\n' || c == '\r'
        || c == '\v' || c == '\f';
}

static int misc_is_split_sep(unsigned char c) {
    return c == ',' || misc_is_ws(c);
}

static unsigned char misc_lower_byte(unsigned char c) {
    return (c >= 'A' && c <= 'Z') ? (unsigned char)(c + 32) : c;
}

static char *misc_strdup(const char *s) {
    size_t len = strlen(s);
    char *d = malloc(len + 1);
    if (d == NULL) {
        tc_fail("out of memory");
    }
    memcpy(d, s, len + 1);
    return d;
}

/* Bounded append with automatic remaining-capacity tracking; the cursor ends
   AT the NUL so the next append overwrites it (tc_cat_cstr_cap semantics). */
static char *misc_cat(char *m, char *end, const char *s) {
    return tc_cat_cstr_cap(m, s, (size_t)(end - m));
}

static void misc_names_init(misc_names *ns) {
    memset(ns, 0, sizeof(*ns));
}

/* Add a name (dedup by exact string — Python set/dict-key semantics).
   Returns 0 added, 1 duplicate. */
static int misc_names_add(misc_names *ns, const char *name) {
    size_t i;
    for (i = 0; i < ns->count; i++) {
        if (strcmp(ns->items[i], name) == 0) {
            return 1;
        }
    }
    if (ns->count >= ns->cap) {
        size_t new_cap = ns->cap == 0 ? 32 : ns->cap * 2;
        char **ni = realloc(ns->items, new_cap * sizeof(char *));
        if (ni == NULL) {
            tc_fail("out of memory");
        }
        ns->items = ni;
        ns->cap = new_cap;
    }
    ns->items[ns->count++] = misc_strdup(name);
    return 0;
}

/* Remove every matching entry (Python dict pop). */
static void misc_names_remove(misc_names *ns, const char *name) {
    size_t i = 0;
    while (i < ns->count) {
        if (strcmp(ns->items[i], name) == 0) {
            free(ns->items[i]);
            memmove(&ns->items[i], &ns->items[i + 1],
                    (ns->count - i - 1) * sizeof(char *));
            ns->count--;
        } else {
            i++;
        }
    }
}

static int misc_names_cmp(const void *a, const void *b) {
    return strcmp(*(const char *const *)a, *(const char *const *)b);
}

static void misc_names_sort(misc_names *ns) {
    qsort(ns->items, ns->count, sizeof(char *), misc_names_cmp);
}

static void misc_names_print(const misc_names *ns) {
    size_t i;
    for (i = 0; i < ns->count; i++) {
        tc_puts(ns->items[i]);
        tc_puts("\n");
    }
}

static void misc_names_free(misc_names *ns) {
    size_t i;
    for (i = 0; i < ns->count; i++) {
        free(ns->items[i]);
    }
    free(ns->items);
    memset(ns, 0, sizeof(*ns));
}

static void misc_excl_init(misc_excl *ex) {
    memset(ex, 0, sizeof(*ex));
    misc_names_init(&ex->groups);
    misc_names_init(&ex->always);
    misc_names_init(&ex->flat);
}

static void misc_excl_free(misc_excl *ex) {
    size_t i;
    misc_names_free(&ex->groups);
    misc_names_free(&ex->always);
    misc_names_free(&ex->flat);
    for (i = 0; i < ex->group_count; i++) {
        free(ex->group_recs[i].name);
        misc_names_free(&ex->group_recs[i].members);
    }
    ex->group_count = 0;
}

// ----------------------------------------------------------------------------
// Python repr() for the strings the error messages interpolate with {!r}
// (channel names, group names, config values).  Single-quote mode is
// preferred; a string containing a single quote but no double quote is
// wrapped in double quotes; a double quote anywhere forces single-quote mode
// (the asm port's documented repr selection).  Escapes \\ \n \r \t and the
// mode's quote char.  Writes into dst (cap bytes) and returns the cursor at
// the NUL (tc_cat_cstr_cap semantics).
// ----------------------------------------------------------------------------
static char *misc_py_repr(char *dst, size_t cap, const char *text) {
    const char *p;
    char *cur = dst;
    char *end = dst + cap;
    int dq_mode = 0;
    int dq_seen = 0;
    if (cap == 0) {
        return dst;
    }
    for (p = text; *p != '\0'; p++) {
        if (*p == '"') {
            dq_mode = 0;
            dq_seen = 1;
        } else if (*p == '\'' && !dq_seen) {
            dq_mode = 1;
        }
    }
    *cur++ = dq_mode ? '"' : '\'';
    for (p = text; *p != '\0' && cur + 1 < end; p++) {
        unsigned char c = (unsigned char)*p;
        const char *e2 = NULL;
        if (c == '\n') {
            e2 = "\\n";
        } else if (c == '\r') {
            e2 = "\\r";
        } else if (c == '\t') {
            e2 = "\\t";
        } else if (c == '\\') {
            e2 = "\\\\";
        } else if (dq_mode && c == '"') {
            e2 = "\\\"";
        } else if (!dq_mode && c == '\'') {
            e2 = "\\'";
        }
        if (e2 != NULL) {
            size_t n = strlen(e2);
            if (cur + n + 1 >= end) {
                break;
            }
            memcpy(cur, e2, n);
            cur += n;
        } else {
            *cur++ = (char)c;
        }
    }
    if (cur + 1 < end) {
        *cur++ = dq_mode ? '"' : '\'';
    }
    *cur = '\0';
    return cur;
}

// ----------------------------------------------------------------------------
// The quiet failure report — "completion failed: ConfigError('<escaped msg>')"
// on stderr (Python run_completion: print(f"completion failed: {exc!r}",
// file=sys.stderr)).  Completion must never fail loudly at a prompt.
// ----------------------------------------------------------------------------
static void misc_failed(misc_state *st, const char *msg) {
    const char *pre, *suf;
    size_t pre_len, suf_len;
    const char *p;
    char *cur;
    char *end = st->esc + sizeof(st->esc);
    int dq_mode = 0;
    int dq_seen = 0;

    /* quote selection (see misc_py_repr) */
    for (p = msg; *p != '\0'; p++) {
        if (*p == '"') {
            dq_mode = 0;
            dq_seen = 1;
        } else if (*p == '\'' && !dq_seen) {
            dq_mode = 1;
        }
    }
    pre = dq_mode ? "completion failed: ConfigError(\""
                  : "completion failed: ConfigError('";
    suf = dq_mode ? "\")\n" : "')\n";
    pre_len = strlen(pre);
    suf_len = strlen(suf);
    if (pre_len + suf_len + 1 >= sizeof(st->esc)) {
        return;   /* (unreachable: the prefix/suffix are 35/4 bytes) */
    }
    cur = st->esc;
    memcpy(cur, pre, pre_len);
    cur += pre_len;
    for (p = msg; *p != '\0'; p++) {
        unsigned char c = (unsigned char)*p;
        const char *e2 = NULL;
        if (c == '\n') {
            e2 = "\\n";
        } else if (c == '\r') {
            e2 = "\\r";
        } else if (c == '\t') {
            e2 = "\\t";
        } else if (c == '\\') {
            e2 = "\\\\";
        } else if (dq_mode && c == '"') {
            e2 = "\\\"";
        } else if (!dq_mode && c == '\'') {
            e2 = "\\'";
        }
        if (e2 != NULL) {
            size_t n = strlen(e2);
            if ((size_t)(end - cur) <= n + suf_len) {
                break;   /* truncate rather than overflow */
            }
            memcpy(cur, e2, n);
            cur += n;
        } else {
            if ((size_t)(end - cur) <= 1 + suf_len) {
                break;
            }
            *cur++ = (char)c;
        }
    }
    memcpy(cur, suf, suf_len);
    cur += suf_len;
    tc_eputs(st->esc);
    (void)cur;
}

// ----------------------------------------------------------------------------
// Python config_exclusions — the quiet [exclude] parser.  Fills st->excl
// (groups/always/flat), validating the shape exactly like the reference so a
// broken config reports instead of exiting.  Returns 0 ok, 2 = error printed.
// ----------------------------------------------------------------------------
static int misc_group_index(const misc_state *st, const char *name) {
    size_t i;
    for (i = 0; i < st->excl.group_count; i++) {
        if (strcmp(st->excl.group_recs[i].name, name) == 0) {
            return (int)i;
        }
    }
    return -1;
}

/* Python `", ".join(sorted(groups)) or "(none defined)"`. */
static char *misc_cat_sorted_groups(const misc_state *st, char *m, char *end) {
    misc_names sorted;
    size_t i;
    misc_names_init(&sorted);
    for (i = 0; i < st->excl.group_count; i++) {
        misc_names_add(&sorted, st->excl.group_recs[i].name);
    }
    misc_names_sort(&sorted);
    if (sorted.count == 0) {
        m = misc_cat(m, end, "(none defined)");
    } else {
        for (i = 0; i < sorted.count; i++) {
            if (i > 0) {
                m = misc_cat(m, end, ", ");
            }
            m = misc_cat(m, end, sorted.items[i]);
        }
    }
    misc_names_free(&sorted);
    return m;
}

/* A TOML raw value -> NUL-terminated string (strings unquoted, other raws
   as-is — Python str(value) for the common cases). */
static void misc_toml_value_to_string(const char *raw, char *dst, size_t cap) {
    if (raw[0] == '"' || raw[0] == '\'') {
        char *unquoted = NULL;
        if (toml_rtos(raw, &unquoted) == 0 && unquoted != NULL) {
            tc_copy_str_cap(dst, unquoted, cap);
            free(unquoted);
            return;
        }
        dst[0] = '\0';
        return;
    }
    tc_copy_str_cap(dst, raw, cap);
}

/* Python split_names over a TOML array's stringified elements: each element
   is str().strip().lower(), empties dropped — elements are NOT re-split on
   commas/spaces (the string form below is the one that splits). */
static void misc_cfg_members(toml_array_t *arr, misc_names *out) {
    int n = toml_array_nelem(arr);
    int i;
    for (i = 0; i < n; i++) {
        const char *raw = toml_raw_at(arr, i);
        char val[MISC_VALUE_SZ];
        char stripped[MISC_VALUE_SZ];
        size_t len;
        size_t lead = 0;
        size_t end;
        size_t out_len;
        size_t j;
        if (raw == NULL) {
            continue;
        }
        misc_toml_value_to_string(raw, val, sizeof(val));
        len = strlen(val);
        while (lead < len && misc_is_ws((unsigned char)val[lead])) {
            lead++;
        }
        end = len;
        while (end > lead && misc_is_ws((unsigned char)val[end - 1])) {
            end--;
        }
        out_len = end - lead;
        if (out_len >= sizeof(stripped)) {
            out_len = sizeof(stripped) - 1;
        }
        for (j = 0; j < out_len; j++) {
            stripped[j] = (char)misc_lower_byte((unsigned char)val[lead + j]);
        }
        stripped[out_len] = '\0';
        if (out_len > 0) {
            misc_names_add(out, stripped);
        }
    }
}

/* Python split_names over a string (re.split(r"[,\s]+", s), then strip +
   lower, empties dropped).  Each token is added to ns. */
static void misc_split_add(misc_names *ns, const char *value) {
    const char *p = value;
    for (;;) {
        const char *start;
        size_t len;
        size_t i;
        char tok[MISC_VALUE_SZ];
        while (*p != '\0' && misc_is_split_sep((unsigned char)*p)) {
            p++;
        }
        if (*p == '\0') {
            return;
        }
        start = p;
        while (*p != '\0' && !misc_is_split_sep((unsigned char)*p)) {
            p++;
        }
        len = (size_t)(p - start);
        if (len >= sizeof(tok)) {
            len = sizeof(tok) - 1;
        }
        for (i = 0; i < len; i++) {
            tok[i] = (char)misc_lower_byte((unsigned char)start[i]);
        }
        tok[len] = '\0';
        misc_names_add(ns, tok);
    }
}

static void misc_split_remove(misc_names *ns, const char *value) {
    const char *p = value;
    for (;;) {
        const char *start;
        size_t len;
        char tok[MISC_VALUE_SZ];
        while (*p != '\0' && misc_is_split_sep((unsigned char)*p)) {
            p++;
        }
        if (*p == '\0') {
            return;
        }
        start = p;
        while (*p != '\0' && !misc_is_split_sep((unsigned char)*p)) {
            p++;
        }
        len = (size_t)(p - start);
        if (len >= sizeof(tok)) {
            len = sizeof(tok) - 1;
        }
        memcpy(tok, start, len);
        tok[len] = '\0';
        misc_names_remove(ns, tok);
    }
}

static int misc_cfg_exclusions(misc_state *st) {
    toml_table_t *root = st->config;
    toml_array_t *arr;
    toml_table_t *tab;
    int total;
    int i;
    char *m;
    char *end = st->msg + sizeof(st->msg);

    if (root == NULL) {
        return 0;   /* no config: empty exclusions */
    }
    /* a scalar "exclude" is the shape error (Python: not a list, not a dict) */
    if (toml_raw_in(root, "exclude") != NULL) {
        m = st->msg;
        m = misc_cat(m, end, "`exclude` in ");
        m = misc_cat(m, end, st->config_where);
        m = misc_cat(m, end, " must be a list of logins or a table of groups");
        *m = '\0';
        misc_failed(st, st->msg);
        return 2;
    }
    arr = toml_array_in(root, "exclude");
    if (arr != NULL) {
        /* exclude = [ ... ] -> flat logins */
        misc_cfg_members(arr, &st->excl.flat);
        return 0;
    }
    tab = toml_table_in(root, "exclude");
    if (tab == NULL) {
        return 0;   /* no exclude key */
    }
    total = toml_table_nkval(tab) + toml_table_narr(tab) + toml_table_ntab(tab);
    for (i = 0; i < total; i++) {
        const char *name = toml_key_in(tab, i);
        toml_array_t *members;
        if (name == NULL) {
            continue;
        }
        if (strcmp(name, "always") == 0) {
            continue;
        }
        members = toml_array_in(tab, name);
        if (members == NULL) {
            m = st->msg;
            m = misc_cat(m, end, "[exclude].");
            m = misc_cat(m, end, name);
            m = misc_cat(m, end, " in ");
            m = misc_cat(m, end, st->config_where);
            m = misc_cat(m, end, " must be a list of logins");
            *m = '\0';
            misc_failed(st, st->msg);
            return 2;
        }
        if (st->excl.group_count < MISC_GROUPS_MAX) {
            misc_group *g = &st->excl.group_recs[st->excl.group_count];
            misc_names_init(&g->members);
            g->name = misc_strdup(name);
            misc_names_add(&st->excl.groups, name);
            misc_cfg_members(members, &g->members);
            st->excl.group_count++;
        }
    }
    /* the "always" array of group names */
    if (toml_key_exists(tab, "always")) {
        toml_array_t *always = toml_array_in(tab, "always");
        if (always == NULL) {
            m = st->msg;
            m = misc_cat(m, end, "[exclude].always in ");
            m = misc_cat(m, end, st->config_where);
            m = misc_cat(m, end, " must be a list of group names");
            *m = '\0';
            misc_failed(st, st->msg);
            return 2;
        }
        {
            int n = toml_array_nelem(always);
            for (i = 0; i < n; i++) {
                const char *raw = toml_raw_at(always, i);
                char aname[MISC_VALUE_SZ];
                if (raw == NULL) {
                    continue;
                }
                misc_toml_value_to_string(raw, aname, sizeof(aname));
                if (misc_group_index(st, aname) < 0) {
                    m = st->msg;
                    m = misc_cat(m, end, "[exclude].always in ");
                    m = misc_cat(m, end, st->config_where);
                    m = misc_cat(m, end, " names unknown group ");
                    m = misc_py_repr(m, (size_t)(end - m), aname);
                    m = st->msg + strlen(st->msg);
                    m = misc_cat(m, end, "; defined groups: ");
                    m = misc_cat_sorted_groups(st, m, end);
                    *m = '\0';
                    misc_failed(st, st->msg);
                    return 2;
                }
                misc_names_add(&st->excl.always, aname);
            }
        }
    }
    return 0;
}

// ----------------------------------------------------------------------------
// Config layer (Python load_config_layer + load_config).
//
//  The C tc_cli_parse resolves settings before the config module can see a
//  --config path (config.c's lazy load caches the default-path result first),
//  so this module is where the --config file is actually loaded for a
//  completion.  A config that fails to LOAD (missing explicit path, TOML or
//  I/O error) exits 1 loudly — the documented divergence, shared with the
//  asm port's eager load (the Python reports quietly and exits 0).  Errors
//  AFTER a successful load ([exclude] shape, channel resolution) stay quiet
//  through misc_failed, exactly like run_completion.
// ----------------------------------------------------------------------------
static int misc_config_open(misc_state *st) {
    const tc_opts *opts = st->opts;
    const char *src = NULL;
    int explicit = 0;
    char path[MISC_PATH_SZ];
    char *m;
    char *end;
    struct stat sb;
    FILE *fp;
    toml_table_t *tab;
    char errbuf[MISC_ERRBUF_SZ];
    size_t len;

    if (opts->flags & TC_F_NO_CONFIG) {
        return 0;   /* --no-config -> {} */
    }
    /* explicit = --config or TWITCH_COUNTS_CONFIG */
    if (opts->flags & TC_F_CONFIG_GIVEN) {
        src = opts->config_path;
        explicit = 1;
    } else {
        const char *env = getenv("TWITCH_COUNTS_CONFIG");
        if (env != NULL && env[0] != '\0') {
            src = env;
            explicit = 1;
        }
    }
    if (src != NULL) {
        tc_expanduser(src, path, sizeof(path));
    } else {
        len = tc_default_config_path(path, sizeof(path));
        if (len == 0 || len >= sizeof(path)) {
            path[0] = '\0';
        }
    }
    if (path[0] == '\0') {
        return 0;   /* no default on this platform -> {} */
    }
    tc_copy_str_cap(st->config_path, path, sizeof(st->config_path));
    {
        const char *shortened = tc_shorten_path(path);
        tc_copy_str_cap(st->config_where, shortened, sizeof(st->config_where));
    }
    /* load_config: a missing default path -> {}; a missing explicit one
       raises ConfigError — loudly here (the documented divergence) */
    if (stat(path, &sb) != 0 || !S_ISREG(sb.st_mode)) {
        if (explicit) {
            char msg[MISC_MSG_SZ];
            m = msg;
            end = msg + sizeof(msg);
            m = misc_cat(m, end, "config file not found: ");
            m = misc_cat(m, end, path);
            *m = '\0';
            tc_fail(msg);
        }
        return 0;
    }
    fp = fopen(path, "rb");
    if (fp == NULL) {
        char msg[MISC_MSG_SZ];
        int err = errno;
        m = msg;
        end = msg + sizeof(msg);
        m = misc_cat(m, end, "could not read config ");
        m = misc_cat(m, end, path);
        m = misc_cat(m, end, ": ");
        m = misc_cat(m, end, tc_oserror_text(err));
        m = misc_cat(m, end, ": '");
        m = misc_cat(m, end, path);
        m = misc_cat(m, end, "'");
        *m = '\0';
        tc_fail(msg);
    }
    errbuf[0] = '\0';
    tab = toml_parse_file(fp, errbuf, sizeof(errbuf));
    fclose(fp);
    if (tab == NULL) {
        char msg[MISC_MSG_SZ];
        m = msg;
        end = msg + sizeof(msg);
        m = misc_cat(m, end, "could not read config ");
        m = misc_cat(m, end, path);
        m = misc_cat(m, end, ": ");
        m = misc_cat(m, end, errbuf);
        *m = '\0';
        tc_fail(msg);
    }
    st->config = tab;
    return 0;
}

