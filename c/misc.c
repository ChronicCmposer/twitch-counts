/* --emit-fish-completions: part A, the default config path the Python
   splices in (shorten_path(DEFAULT_CONFIG_PATH)), then part B. */
int tc_misc_fish(void) {
    char path[MISC_PATH_SZ];
    size_t len;

    memset(path, 0, sizeof(path));
    len = tc_default_config_path(path, sizeof(path));
    if (len == 0 || len >= sizeof(path)) {
        /* no XDG/HOME default: fall back to the passwd home like the
           Python's Platform class (Linux _xdg / macOS expanduser) */
        char home[MISC_PATH_SZ];
        if (tc_expanduser("~", home, sizeof(home)) > 0) {
            len = (size_t)snprintf(path, sizeof(path),
                                   "%s/.config/twitch-counts.toml", home);
        }
    }
    tc_puts(tc_fish_text_a);
    if (len > 0 && len < sizeof(path)) {
        tc_puts(tc_shorten_path(path));
    }
    tc_puts(tc_fish_text_b);
    return TC_EXIT_OK;
}

/* --complete KIND: candidates for channels/groups/dates/weeks/periods/
   users/includes, one per line; a failure prints the quiet ConfigError
   report and returns 0 (never a loud exit). */
int tc_misc_complete(const tc_opts *opts) {
    misc_state st;
    int status;

    memset(&st, 0, sizeof(st));
    st.opts = opts;
    misc_names_init(&st.names);
    misc_excl_init(&st.excl);

    status = misc_config_open(&st);
    if (status != 0) {
        misc_state_free(&st);
        return TC_EXIT_OK;
    }
    switch (opts->complete_kind) {
    case TC_COMPLETE_CHANNELS:
        misc_complete_channels(&st);
        break;
    case TC_COMPLETE_GROUPS:
        misc_complete_groups(&st);
        break;
    case TC_COMPLETE_DATES:
        if (misc_require_channel(&st) == 0) {
            misc_complete_dates(&st);
        }
        break;
    case TC_COMPLETE_WEEKS:
        if (misc_require_channel(&st) == 0) {
            misc_complete_weeks(&st);
        }
        break;
    case TC_COMPLETE_PERIODS:
        if (misc_require_channel(&st) == 0) {
            misc_complete_periods(&st);
        }
        break;
    case TC_COMPLETE_USERS:
        if (misc_require_channel(&st) == 0) {
            misc_complete_users(&st);
        }
        break;
    case TC_COMPLETE_INCLUDES:
        if (misc_require_channel(&st) == 0) {
            misc_complete_includes(&st);
        }
        break;
    default:
        /* the CLI validates the kind, so a bad enum is a programming error;
           completion still never fails loudly — report it and return 0 */
        misc_failed(&st, "internal error: unknown --complete kind");
        break;
    }
    misc_state_free(&st);
    return TC_EXIT_OK;
}

/* The current time in UTC as (packed YYYYMMDD, seconds-of-day).  Documented
   deviation: the Python's misc_complete_users uses datetime.now() (local
   time); the port uses UTC so the window is reproducible. */
void tc_misc_now_utc(int64_t *ymd, int64_t *sod) {
    struct timespec ts;
    time_t now;
    if (clock_gettime(CLOCK_REALTIME, &ts) == 0) {
        now = ts.tv_sec;
    } else {
        now = time(NULL);
    }
    tc_epoch_to_ymd_sod((int64_t)now, ymd, sod);
}