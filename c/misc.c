/* Python completion_candidates' channel resolve: CLI > env > config.  The C
   tc_cli_parse resolves the settings before the config module can see a
   --config path (s_opts is registered by tc_aliases_apply afterwards), so a
   channel that lives in a --config file never reaches opts->channel.  The
   completion module therefore re-resolves from its own parsed table: the
   CLI/env values tc_cli_parse already resolved are authoritative, and
   TC_SRC_CONFIG / TC_SRC_DEFAULT fall through to the config layer. */
static const char *misc_resolve_channel(misc_state *st, char *dst, size_t cap) {
    const tc_opts *opts = st->opts;
    enum tc_source src = opts->src[TC_SET_CHANNEL];

    if (src != TC_SRC_CONFIG && src != TC_SRC_DEFAULT) {
        /* CLI / env / alias: tc_cli_parse's resolved value is authoritative */
        tc_copy_str_cap(dst, opts->channel, cap);
        return dst;
    }
    if (st->config != NULL) {
        const char *raw = toml_raw_in(st->config, "channel");
        if (raw != NULL) {
            misc_toml_value_to_string(raw, dst, cap);
            if (dst[0] != '\0') {
                return dst;
            }
        }
    }
    if (src == TC_SRC_CONFIG) {
        /* no --config, same default-path file tc_cli_parse loaded */
        tc_copy_str_cap(dst, opts->channel, cap);
        return dst;
    }
    dst[0] = '\0';
    return dst;
}

/* Python: os.path.expanduser(str(logs_dir.value)) — resolved the same way
   completion_candidates resolves logs-dir (CLI > env > config > platform
   default), with "None" for the Linux platform stub's absent default. */
static void misc_expand_root(misc_state *st) {
    const tc_opts *opts = st->opts;
    enum tc_source src = opts->src[TC_SET_LOGS_DIR];

    if (src != TC_SRC_CONFIG && src != TC_SRC_DEFAULT_BUILTIN) {
        /* CLI / env: tc_cli_parse's resolved value is authoritative */
        tc_expanduser(opts->logs_dir, st->logs_root, sizeof(st->logs_root));
        return;
    }
    if (src == TC_SRC_CONFIG) {
        /* config layer: the completion's own table honors --config */
        if (st->config != NULL) {
            const char *raw = toml_raw_in(st->config, "logs_dir");
            if (raw != NULL) {
                char val[MISC_PATH_SZ];
                misc_toml_value_to_string(raw, val, sizeof(val));
                if (val[0] != '\0') {
                    tc_expanduser(val, st->logs_root, sizeof(st->logs_root));
                    return;
                }
            }
        }
        /* no config logs_dir: the platform default tc_cli_parse filled */
        tc_expanduser(opts->logs_dir, st->logs_root, sizeof(st->logs_root));
        return;
    }
    /* TC_SRC_DEFAULT_BUILTIN: the platform default (empty on Linux) */
    if (opts->logs_dir[0] != '\0') {
        tc_expanduser(opts->logs_dir, st->logs_root, sizeof(st->logs_root));
    } else {
        tc_copy_str_cap(st->logs_root, "None", sizeof(st->logs_root));
    }
}

static int misc_is_dir(const char *path) {
    struct stat sb;
    return stat(path, &sb) == 0 && S_ISDIR(sb.st_mode);
}

/* Every subdirectory of path (d_type DT_DIR, skipping "." and ".."), added
   and sorted.  Returns 1 when the directory could be opened, 0 otherwise. */
static int misc_list_dirs(const char *path, misc_names *dirs) {
    DIR *d = opendir(path);
    struct dirent *de;
    if (d == NULL) {
        return 0;
    }
    while ((de = readdir(d)) != NULL) {
        if (de->d_type != DT_DIR) {
            continue;
        }
        if (strcmp(de->d_name, ".") == 0 || strcmp(de->d_name, "..") == 0) {
            continue;
        }
        misc_names_add(dirs, de->d_name);
    }
    closedir(d);
    misc_names_sort(dirs);
    return 1;
}

static void misc_lowercase_into(const char *src, char *dst, size_t cap) {
    size_t i = 0;
    for (;;) {
        unsigned char c;
        if (i + 1 >= cap) {
            dst[i] = '\0';
            return;
        }
        c = (unsigned char)src[i];
        if (c >= 'A' && c <= 'Z') {
            c = (unsigned char)(c + 32);
        }
        dst[i] = (char)c;
        if (c == '\0') {
            return;
        }
        i++;
    }
}

/* aliases.get(key, key): the config's [aliases] value for the channel, or
   the channel itself (Python completion_candidates). */
static const char *misc_aliased_channel(const misc_state *st, const char *key,
                                        char *dst, size_t cap) {
    toml_table_t *aliases;
    const char *raw;
    if (st->config == NULL) {
        return key;
    }
    aliases = toml_table_in(st->config, "aliases");
    if (aliases == NULL) {
        return key;
    }
    raw = toml_raw_in(aliases, key);
    if (raw == NULL) {
        return key;
    }
    misc_toml_value_to_string(raw, dst, cap);
    return dst;
}

// ----------------------------------------------------------------------------
// Channel resolution (Python resolve_channel_dir) — the quiet version: a
// missing logs root / channel dir reports a ConfigError instead of exiting.
// Returns 0 ok (channel_dir/channel_name filled), 1 no channel (empty
// output), 2 error printed.
// ----------------------------------------------------------------------------
static int misc_require_channel(misc_state *st) {
    char resolved[TC_CHANNEL_SZ];
    const char *channel;
    char alias_buf[MISC_PATH_SZ];
    const char *aliased;
    char lower[TC_CHANNEL_SZ];
    misc_names dirs;
    size_t i;
    char *m;
    char *end;

    channel = misc_resolve_channel(st, resolved, sizeof(resolved));
    if (channel[0] == '\0') {
        return 1;   /* Python: if not channel: return [] */
    }
    misc_expand_root(st);
    if (!misc_is_dir(st->logs_root)) {
        m = st->msg;
        end = st->msg + sizeof(st->msg);
        m = misc_cat(m, end, "logs directory not found: ");
        m = misc_cat(m, end, st->logs_root);
        *m = '\0';
        misc_failed(st, st->msg);
        return 2;
    }
    misc_names_init(&dirs);
    misc_list_dirs(st->logs_root, &dirs);
    aliased = misc_aliased_channel(st, channel, alias_buf,
                                   sizeof(alias_buf));
    misc_lowercase_into(aliased, lower, sizeof(lower));
    for (i = 0; i < dirs.count; i++) {
        if (tc_ascii_casecmp(dirs.items[i], lower) == 0) {
            snprintf(st->channel_dir, sizeof(st->channel_dir), "%s/%s",
                     st->logs_root, dirs.items[i]);
            tc_copy_str_cap(st->channel_name, dirs.items[i],
                            sizeof(st->channel_name));
            misc_names_free(&dirs);
            return 0;
        }
    }
    /* "no logs for channel '<ch>' in <root>\navailable: <join|(none)>" */
    m = st->msg;
    end = st->msg + sizeof(st->msg);
    m = misc_cat(m, end, "no logs for channel ");
    m = misc_py_repr(m, (size_t)(end - m), aliased);
    m = st->msg + strlen(st->msg);
    m = misc_cat(m, end, " in ");
    m = misc_cat(m, end, st->logs_root);
    m = misc_cat(m, end, "\navailable: ");
    if (dirs.count == 0) {
        m = misc_cat(m, end, "(none)");
    } else {
        for (i = 0; i < dirs.count; i++) {
            if (i > 0) {
                m = misc_cat(m, end, ", ");
            }
            m = misc_cat(m, end, dirs.items[i]);
        }
    }
    *m = '\0';
    misc_names_free(&dirs);
    misc_failed(st, st->msg);
    return 2;
}

// ----------------------------------------------------------------------------
// The dated-log listing (Python log_files): every name shaped
// "<anything>-YYYY-MM-DD.log" with a real calendar date, sorted ascending.
// Built here with core.c's tc_parse_log_filename_n so the FILENAME_RE
// filtering, date validation and sort are the differential-tested ones.
// Returns 0 ok, 2 = error printed (the channel dir cannot be opened).
// ----------------------------------------------------------------------------
static int misc_log_cmp(const void *a, const void *b) {
    const misc_log_entry *ea = a;
    const misc_log_entry *eb = b;
    if (ea->ymd < eb->ymd) {
        return -1;
    }
    if (ea->ymd > eb->ymd) {
        return 1;
    }
    return strcmp(ea->name, eb->name);
}

/* The Python exception class for an errno (mirrors core.c's map) — used for
   the quiet OSError repr when a listing cannot be opened. */
static const char *misc_errno_exc(int err) {
    switch (err) {
    case EPERM:
    case EACCES:
        return "PermissionError";
    case ENOENT:
        return "FileNotFoundError";
    case EISDIR:
        return "IsADirectoryError";
    case ENOTDIR:
        return "NotADirectoryError";
    case EEXIST:
        return "FileExistsError";
    case EINTR:
        return "InterruptedError";
    case EPIPE:
        return "BrokenPipeError";
    default:
        return "OSError";
    }
}

static int misc_listing_build(misc_state *st, misc_log_entry **out,
                              size_t *count_out) {
    DIR *d = opendir(st->channel_dir);
    struct dirent *de;
    size_t count = 0;
    size_t cap = 0;
    misc_log_entry *entries = NULL;
    char *m;
    char *end;

    if (d == NULL) {
        /* The channel dir was verified a moment ago; a failure here is a
           race.  The Python raises an OSError that run_completion reports
           quietly as its repr: ExcClass(errno, 'strerror'). */
        int err = errno;
        m = st->msg;
        end = st->msg + sizeof(st->msg);
        m = misc_cat(m, end, misc_errno_exc(err));
        m = misc_cat(m, end, "(");
        m = tc_fmt_u64(m, (uint64_t)err);
        m = misc_cat(m, end, ", '");
        m = misc_cat(m, end, strerror(err));
        m = misc_cat(m, end, "')");
        *m = '\0';
        misc_failed(st, st->msg);
        *out = NULL;
        *count_out = 0;
        return 2;
    }
    while ((de = readdir(d)) != NULL) {
        size_t len = strlen(de->d_name);
        int64_t ymd = tc_parse_log_filename_n(de->d_name, len);
        if (ymd == 0) {
            continue;
        }
        if (count >= cap) {
            size_t new_cap = cap == 0 ? MISC_LISTING_INIT : cap * 2;
            misc_log_entry *ne = realloc(entries,
                                         new_cap * sizeof(*ne));
            if (ne == NULL) {
                closedir(d);
                free(entries);
                tc_fail("out of memory");
            }
            entries = ne;
            cap = new_cap;
        }
        entries[count].ymd = ymd;
        tc_copy_str_cap(entries[count].name, de->d_name,
                        sizeof(entries[count].name));
        count++;
    }
    closedir(d);
    qsort(entries, count, sizeof(misc_log_entry), misc_log_cmp);
    *out = entries;
    *count_out = count;
    return 0;
}

// ----------------------------------------------------------------------------
// Date/week formatting.
// ----------------------------------------------------------------------------
/* "YYYY-MM-DD" into dst (11 bytes + NUL). */
static void misc_fmt_ymd(int64_t ymd, char *dst) {
    int y, mo, d;
    tc_ymd_split(ymd, &y, &mo, &d);
    dst = tc_fmt4(dst, (uint64_t)y);
    *dst++ = '-';
    dst = tc_fmt2(dst, (uint64_t)mo);
    *dst++ = '-';
    dst = tc_fmt2(dst, (uint64_t)d);
    *dst = '\0';
}

/* "YYYY-WNN" into dst (11 bytes + NUL). */
static void misc_fmt_week(int iso_year, int iso_week, char *dst) {
    dst = tc_fmt4(dst, (uint64_t)iso_year);
    *dst++ = '-';
    *dst++ = 'W';
    dst = tc_fmt2(dst, (uint64_t)iso_week);
    *dst = '\0';
}

/* ISO-8601 week of a packed YYYYMMDD date (the asm port's algorithm,
   verified against Python's datetime.isocalendar for years 1..9999). */
static void misc_iso_week(int64_t ymd, int *iso_year, int *iso_week) {
    int y, m, d;
    int64_t epoch;
    int iso_wd;
    int64_t thu;
    int ty, tm, td;
    int64_t jan4;
    int jw;
    int64_t week1;
    int64_t week;

    tc_ymd_split(ymd, &y, &m, &d);
    epoch = tc_days_from_civil(y, m, d);
    /* iso weekday, Mon=1 (1970-01-01 is a Thursday) */
    iso_wd = (int)(((epoch + 3) % 7 + 7) % 7 + 1);
    thu = epoch + (4 - iso_wd);
    tc_civil_from_days(thu, &ty, &tm, &td);
    jan4 = tc_days_from_civil(ty, 1, 4);
    jw = (int)(((jan4 + 3) % 7 + 7) % 7 + 1);
    week1 = jan4 - (jw - 1);
    week = (epoch - week1) / 7 + 1;
    *iso_year = ty;
    *iso_week = (int)week;
}

