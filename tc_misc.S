// ============================================================================
// Calendar helpers (Hinnant civil_from_days inverse; verified against the
// Python's datetime for years 1..9999).
// ============================================================================

// misc_ymd_to_days(x0=ymd) -> x0 = days since 1970-01-01.
misc_ymd_to_days:
    PROLOGUE 1
    mov x19, x0                         // ymd
    mov x0, #YMD_YEAR_SCALE
    udiv x1, x19, x0                    // y
    mov x0, #YMD_MONTH_SCALE
    udiv x2, x19, x0                    // ymd/100
    udiv x3, x2, x0                     // mo = (ymd/100)/100
    msub x3, x3, x0, x2                 // mo = (ymd/100) % 100
    msub x2, x2, x0, x19                // d = ymd % 100
    mov x0, x1
    mov x1, x3
    bl tc_days_from_civil
    EPILOGUE 1
    ret

// misc_days_to_ymd(x0=days) -> x0 = ymd.
misc_days_to_ymd:
    PROLOGUE 2
    bl tc_civil_from_days               // x0=y, x1=m, x2=d
    mov x19, #YMD_YEAR_SCALE
    mul x0, x0, x19
    mov x19, #YMD_MONTH_SCALE
    madd x0, x1, x19, x0
    add x0, x0, x2
    EPILOGUE 2
    ret

// misc_iso_week(x0=ymd) -> (x0=iso_year, x1=iso_week).
misc_iso_week:
    PROLOGUE 4
    mov x19, x0                         // ymd
    bl misc_ymd_to_days
    mov x20, x0                         // epoch
    // iso_wd = ((epoch + 3) mod 7) + 1   (floor mod; Mon=1)
    add x0, x20, #3
    mov x1, #7
    sdiv x2, x0, x1
    msub x2, x2, x1, x0
    cmp x2, #0
    b.ge .Liw_wd
    add x2, x2, #7
.Liw_wd:
    add x21, x2, #1                     // iso_wd
    // thu = epoch + (4 - iso_wd)
    sub x0, x20, x21
    add x22, x0, #4
    mov x0, x22
    bl tc_civil_from_days               // x0 = iso_year
    mov x23, x0
    // jan4 = days_from_civil(iso_year, 1, 4)
    mov x0, x23
    mov x1, #1
    mov x2, #4
    bl tc_days_from_civil
    mov x24, x0                         // jan4
    // jw = ((jan4 + 3) mod 7) + 1
    add x0, x24, #3
    mov x1, #7
    sdiv x2, x0, x1
    msub x2, x2, x1, x0
    cmp x2, #0
    b.ge .Liw_jw
    add x2, x2, #7
.Liw_jw:
    add x25, x2, #1                     // jw
    // week1 = jan4 - (jw - 1)
    sub x0, x24, x25
    add x26, x0, #1
    // week = (epoch - week1) / 7 + 1
    sub x0, x20, x26
    mov x1, #7
    sdiv x1, x0, x1
    add x1, x1, #1
    mov x0, x23
    EPILOGUE 4
    ret

