    strb w2, [x0], #1
.Lcci_done:
    ret

// misc_casecmp(x0=a, x1=b) -> x0 = 0 when equal ignoring ASCII case.
misc_casecmp:
    PROLOGUE 0
    mov x2, x0
    mov x3, x1
.Lcc_loop:
    ldrb w0, [x2], #1
    ldrb w1, [x3], #1
    // lowercase both
    cmp w0, #'A'
    b.lt .Lcc_la
    cmp w0, #'Z'
    b.gt .Lcc_la
    add w0, w0, #('a' - 'A')
.Lcc_la:
    cmp w1, #'A'
    b.lt .Lcc_lb
    cmp w1, #'Z'
    b.gt .Lcc_lb
    add w1, w1, #('a' - 'A')
.Lcc_lb:
    cmp w0, w1
    b.ne .Lcc_ne
    cbnz w0, .Lcc_loop
    mov x0, #0
    b .Lcc_out
.Lcc_ne:
    mov x0, #1
.Lcc_out:
    EPILOGUE 0
    ret

// misc_fmt_dec_pad(x0=dst, x1=value, x2=width) -> x0 = cursor past the
//   zero-padded decimal digits (value < 10^width).
misc_fmt_dec_pad:
    PROLOGUE 2
    mov x19, x0                         // dst
    mov x20, x1                         // value
    mov x21, x2                         // width
    mov x22, #1                         // divisor
    sub x0, x21, #1
.Lfdp_divloop:
    cbz x0, .Lfdp_emit
    mov x1, #10
    mul x22, x22, x1
    sub x0, x0, #1
    b .Lfdp_divloop
.Lfdp_emit:
    cbz x21, .Lfdp_done
    udiv x3, x20, x22                   // digit
    msub x20, x3, x22, x20              // remainder
    add x3, x3, #'0'
    strb w3, [x19], #1
    mov x3, #10
    udiv x22, x22, x3
    sub x21, x21, #1
    b .Lfdp_emit
.Lfdp_done:
    mov x0, x19
    EPILOGUE 2
    ret

// misc_fmt_ymd(x0=ymd, x1=dst) -> x0 = cursor past "YYYY-MM-DD".
misc_fmt_ymd:
    PROLOGUE 2
    mov x19, x0                         // ymd
    mov x20, x1                         // dst
    mov x21, #YMD_YEAR_SCALE
    udiv x1, x19, x21                   // y
    mov x0, x20
    mov x2, #4
    bl misc_fmt_dec_pad                 // x0 = cursor
    mov w1, #'-'
    strb w1, [x0], #1
    mov x20, x0
    mov x22, #YMD_MONTH_SCALE
    udiv x1, x19, x22                   // ymd/100
    udiv x2, x1, x22
    msub x1, x2, x22, x1                // mo = (ymd/100) % 100
    mov x0, x20
    mov x2, #2
    bl misc_fmt_dec_pad
    mov w1, #'-'
    strb w1, [x0], #1
    mov x20, x0
    udiv x1, x19, x22                   // ymd/100
    msub x1, x1, x22, x19               // d = ymd % 100
    mov x0, x20
    mov x2, #2
    bl misc_fmt_dec_pad
    EPILOGUE 2
    ret

// misc_fmt_week(x0=iso_year, x1=iso_week, x2=dst) -> x0 = cursor past "YYYY-WNN".
misc_fmt_week:
    PROLOGUE 2
    mov x19, x0                         // iso_year
    mov x20, x1                         // iso_week
    mov x21, x2                         // dst
    mov x0, x21
    mov x1, x19
    mov x2, #4
    bl misc_fmt_dec_pad
    mov w1, #'-'
    strb w1, [x0], #1
    mov w1, #'W'
    strb w1, [x0], #1
    mov x21, x0
    mov x0, x21
    mov x1, x20
    mov x2, #2
    bl misc_fmt_dec_pad
    EPILOGUE 2
    ret

