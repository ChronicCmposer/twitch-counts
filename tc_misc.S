// ============================================================================
// tc_misc_fish() -> 0 — print the fish completions (tc_fish.inc) to stdout.
// ============================================================================
    .p2align 2
    .global tc_misc_fish
    FUNC_TYPE(tc_misc_fish)
tc_misc_fish:
    PROLOGUE 0
    // The blob is split where fish_completions() embeds
    // shorten_path(DEFAULT_CONFIG_PATH) (twitch-counts.py:3954), which the
    // Python computes at runtime for the machine it runs on.
    LEA x0, tc_fish_text_a
    bl tc_puts
    LEA x0, misc_expanded
    mov x1, #MISC_PATH_SZ
    bl tc_default_config_path
    LEA x0, misc_expanded
    bl tc_shorten_path
    bl tc_puts
    LEA x0, tc_fish_text_b
    bl tc_puts
    mov x0, #0
    EPILOGUE 0
    ret

// ============================================================================
// tc_misc_now_utc() -> (x0=ymd, x1=sod) — the current time in UTC.
//   Documented deviation: the Python's misc_complete_users uses datetime.now()
//   (local time); the port uses UTC so the window is reproducible.
// ============================================================================
    .p2align 2
    .global tc_misc_now_utc
    FUNC_TYPE(tc_misc_now_utc)
tc_misc_now_utc:
    PROLOGUE 2
    mov x0, #CLOCK_REALTIME
    LEA x1, misc_ts
    bl clock_gettime
    LEA x19, misc_ts
    ldr x20, [x19]                      // seconds
    ldr x21, =SECS_PER_DAY
    sdiv x22, x20, x21                  // days
    msub x20, x22, x21, x20             // seconds-of-day
    mov x0, x22
    bl tc_civil_from_days               // x0=y, x1=m, x2=d
    mov x19, #YMD_YEAR_SCALE
    mul x0, x0, x19
    mov x19, #YMD_MONTH_SCALE
    madd x0, x1, x19, x0
    add x0, x0, x2                      // ymd
    mov x1, x20                         // sod
    EPILOGUE 2
    ret

// ============================================================================
// tc_misc_complete(x0=kind) -> 0 — the --complete KIND entry point.
// ============================================================================
    .p2align 2
    .global tc_misc_complete
    FUNC_TYPE(tc_misc_complete)
tc_misc_complete:
    PROLOGUE 2
    mov x19, x0                         // kind
    bl misc_arena_reset
    // ---- step 1: the config layer (Python load_config_layer) --------------
    bl misc_config_open                 // x0=tab, x1=status
    mov x20, x0                         // x20 = tab (0 = no config)
    cmp x1, #2
    b.eq .Lmc_done                      // failure already printed
    // ---- step 2: dispatch -------------------------------------------------
    cmp x19, #TC_COMPLETE_CHANNELS
    b.eq .Lmc_channels
    cmp x19, #TC_COMPLETE_GROUPS
    b.eq .Lmc_groups
    // the remaining kinds need a resolved channel
    bl misc_require_channel             // x0 = 0 ok / 1 empty / 2 error
    cmp x0, #0
    b.ne .Lmc_done
    cmp x19, #TC_COMPLETE_DATES
    b.eq .Lmc_dates
    cmp x19, #TC_COMPLETE_WEEKS
    b.eq .Lmc_weeks
    cmp x19, #TC_COMPLETE_PERIODS
    b.eq .Lmc_periods
    cmp x19, #TC_COMPLETE_USERS
    b.eq .Lmc_users
    cmp x19, #TC_COMPLETE_INCLUDES
    b.eq .Lmc_includes
    b .Lmc_done
.Lmc_channels:
    mov x0, x20
    bl misc_complete_channels
    b .Lmc_done
.Lmc_groups:
    mov x0, x20
    bl misc_complete_groups
    b .Lmc_done
.Lmc_dates:
    bl misc_complete_dates
    b .Lmc_done
.Lmc_weeks:
    bl misc_complete_weeks
    b .Lmc_done
.Lmc_periods:
    bl misc_complete_periods
    b .Lmc_done
.Lmc_users:
    mov x0, x20
    bl misc_complete_users
    b .Lmc_done
.Lmc_includes:
    mov x0, x20
    bl misc_complete_includes
    b .Lmc_done
.Lmc_done:
    mov x0, x20
    cbz x0, .Lmc_out
    bl toml_free
.Lmc_out:
    mov x0, #0
    EPILOGUE 2
    ret

// ============================================================================
// misc_complete_channels(x0=tab) — sorted(aliases keys + logs-root subdirs).
// ============================================================================
misc_complete_channels:
    PROLOGUE 2
    mov x19, x0                         // tab
    bl misc_names_reset
    cbz x19, .Lcc_dirs
    mov x0, x19
    LEA x1, s_key_aliases
    bl toml_table_in
    cbz x0, .Lcc_dirs
    mov x20, x0                         // aliases table
    mov x21, #0                         // key index
.Lcc_alias_loop:
    mov x0, x20
    mov x1, x21
    bl toml_key_in
    cbz x0, .Lcc_dirs
    bl misc_names_add
    add x21, x21, #1
    b .Lcc_alias_loop
.Lcc_dirs:
    // logs-root subdirectories (Python: if os.path.isdir(logs_root))
    bl misc_expand_root
    LEA x0, misc_root
    bl misc_list_dirs                   // adds + sorts when the dir exists
    bl misc_names_sort
    bl misc_names_print
    mov x0, #0
    EPILOGUE 2
    ret

// ============================================================================
// misc_complete_groups(x0=tab) — sorted [exclude] group names (config_exclusions).
// ============================================================================
misc_complete_groups:
    PROLOGUE 3
    mov x19, x0                         // tab
    bl misc_cfg_exclusions              // x0 = status
    cmp x0, #0
    b.ne .Lcg_done                      // error printed
    bl misc_names_reset
    LEA x20, misc_group_n
    ldr x21, [x20]                      // group count
    LEA x22, misc_groups
    mov x23, #0                         // i
.Lcg_loop:
    cmp x23, x21
    b.ge .Lcg_sort
    mov x0, #GR_SZ
    mul x0, x23, x0
    add x0, x22, x0
    ldr x0, [x0, #GR_NAME]
    bl misc_names_add
    add x23, x23, #1
    b .Lcg_loop
.Lcg_sort:
    bl misc_names_sort
    bl misc_names_print
.Lcg_done:
    mov x0, #0
    EPILOGUE 3
    ret// ============================================================================
// misc_complete_dates() — every dated log file's date, ascending, one per line.
// ============================================================================
misc_complete_dates:
    PROLOGUE 3
    bl misc_set_all_window
    bl tc_count_run                     // fills tc_listing
    LEA x19, tc_listing
    ldr x20, [x19, #TC_L_COUNT]
    ldr x21, [x19, #TC_L_ENTRIES]
    mov x22, #0
.Lcd_loop:
    cmp x22, x20
    b.ge .Lcd_done
    mov x23, #TC_L_ENTRY_SZ
    mul x23, x22, x23
    add x23, x21, x23
    ldr x23, [x23, #TC_L_YMD]
    mov x0, x23
    LEA x1, misc_buf
    bl misc_fmt_ymd
    LEA x0, misc_buf
    bl misc_print_line
    add x22, x22, #1
    b .Lcd_loop
.Lcd_done:
    mov x0, #0
    EPILOGUE 3
    ret

// ============================================================================
// misc_complete_weeks() — ISO weeks of the dated logs, deduped, in date order.
