    bl tc_count_run
    bl misc_names_reset
    LEA x19, tc_listing
    ldr x20, [x19, #TC_L_COUNT]
    ldr x21, [x19, #TC_L_ENTRIES]
    mov x22, #0
.Lcw_loop:
