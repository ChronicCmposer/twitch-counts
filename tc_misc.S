// ============================================================================
// misc_complete_users(x0=tab) — 7-day counting pass, then sorted config-known.
// ============================================================================
misc_complete_users:
    PROLOGUE 5
    mov x19, x0                         // tab
    // config exclusions -> flat + group members (the "known" set)
    mov x0, x19
    bl misc_cfg_exclusions              // x0 = status
    cmp x0, #0
    b.ne .Lcu_done                      // error printed
    // ---- window: end = now UTC, begin = end - 7 days ----------------------
    bl misc_set_users_window
    // ---- count ------------------------------------------------------------
    bl tc_count_run
    // ---- most_common() order: stable sort of (index, total) by total desc --
    LEA x19, tc_users
    ldr x20, [x19, #TC_US_COUNT]
    ldr x21, [x19, #TC_US_ENTRIES]
    cmp x20, #MISC_MAX_USERS
    b.le .Lcu_cap_ok
    mov x20, #MISC_MAX_USERS
.Lcu_cap_ok:
    mov x22, #0
.Lcu_fill_loop:
    cmp x22, x20
    b.ge .Lcu_fill_done
    LEA x23, misc_uidx
    str x22, [x23, x22, lsl #3]
    mov x23, #TC_US_ENTRY_SZ
    mul x23, x22, x23
    add x23, x21, x23
    ldr x24, [x23, #TC_US_LIVE]
    ldr x25, [x23, #TC_US_OFFLINE]
    add x24, x24, x25
    ldr x25, [x23, #TC_US_UNKNOWN]
    add x24, x24, x25
    LEA x23, misc_uval
    str x24, [x23, x22, lsl #3]
    add x22, x22, #1
    b .Lcu_fill_loop
.Lcu_fill_done:
    LEA x0, misc_uidx
    LEA x1, misc_uval
    mov x2, x20
    bl misc_sort_users
    // print the counted logins in that order
    mov x22, #0
.Lcu_print_loop:
    cmp x22, x20
    b.ge .Lcu_print_done
    LEA x23, misc_uidx
    ldr x23, [x23, x22, lsl #3]
    mov x24, #TC_US_ENTRY_SZ
    mul x24, x23, x24
    add x24, x21, x24
    mov x0, x24                         // login lives at entry + 0
    bl misc_print_line
    add x22, x22, #1
    b .Lcu_print_loop
.Lcu_print_done:
    // ---- sorted(known - set(counts)) --------------------------------------
    bl misc_names_reset
    // flat exclusions
    LEA x22, misc_flat_n
    ldr x23, [x22]
    LEA x24, misc_flat
    mov x25, #0
.Lcu_flat_loop:
    cmp x25, x23
    b.ge .Lcu_flat_done
    ldr x0, [x24, x25, lsl #3]
    bl misc_names_add
    add x25, x25, #1
    b .Lcu_flat_loop
.Lcu_flat_done:
    // every group's members
    LEA x22, misc_group_n
    ldr x23, [x22]
    LEA x24, misc_groups
    mov x25, #0
.Lcu_grp_loop:
    cmp x25, x23
    b.ge .Lcu_grp_done
    mov x26, #GR_SZ
    mul x26, x25, x26
    add x26, x24, x26
    ldr x27, [x26, #GR_MEMBERS]
    ldr x28, [x26, #GR_MEMBER_N]
    mov x26, #0
.Lcu_mem_loop:
    cmp x26, x28
    b.ge .Lcu_grp_next
    ldr x0, [x27, x26, lsl #3]
    bl misc_names_add
    add x26, x26, #1
    b .Lcu_mem_loop
.Lcu_grp_next:
    add x25, x25, #1
    b .Lcu_grp_loop
.Lcu_grp_done:
    bl misc_names_sort
    // print known logins that are NOT in the counted set
    LEA x22, misc_n
    ldr x23, [x22]
    LEA x24, misc_names
    mov x25, #0
.Lcu_known_loop:
    cmp x25, x23
    b.ge .Lcu_known_done
    ldr x26, [x24, x25, lsl #3]
    mov x0, x26
    bl misc_in_users                    // x0 = 1 when already counted
    cbnz x0, .Lcu_known_next
    mov x0, x26
    bl misc_print_line
.Lcu_known_next:
    add x25, x25, #1
    b .Lcu_known_loop
.Lcu_known_done:
    mov x0, #0
.Lcu_done:
    EPILOGUE 5
    ret// ============================================================================
// misc_complete_includes(x0=tab) — sorted merged exclusion logins (build_exclusions).
// ============================================================================
misc_complete_includes:
    PROLOGUE 5
    mov x19, x0                         // tab
    // ---- --no-exclude: conflict check, then empty (Python build_exclusions)
    LEA x0, tc_opts
    ldr x1, [x0, #TC_O_FLAGS]
    tst x1, #TC_F_NO_EXCLUDE
    b.eq .Lci_normal
    LEA x20, misc_buf
    mov x21, x20                        // cursor
    mov x22, #0                         // wrote_any
    tst x1, #TC_F_EXCL_GIVEN
    b.eq .Lci_nx_group
    mov x0, x21
    mov x1, x22
    bl misc_cat_comma_if
    mov x21, x0
    LEA x1, s_flag_exclude
    mov x0, x21
    bl misc_cat
    mov x21, x0
    mov x22, #1
.Lci_nx_group:
    LEA x0, tc_opts
    ldr x1, [x0, #TC_O_FLAGS]
    tst x1, #TC_F_EXCL_GROUP_GIVEN
    b.eq .Lci_nx_bcast
    mov x0, x21
    mov x1, x22
    bl misc_cat_comma_if
    mov x21, x0
    LEA x1, s_flag_exclude_group
    mov x0, x21
    bl misc_cat
    mov x21, x0
    mov x22, #1
.Lci_nx_bcast:
    LEA x0, tc_opts
    ldr x1, [x0, #TC_O_FLAGS]
    tst x1, #TC_F_EXCLUDE_BCAST
    b.eq .Lci_nx_include
    mov x0, x21
    mov x1, x22
    bl misc_cat_comma_if
    mov x21, x0
    LEA x1, s_flag_exclude_bcast
    mov x0, x21
    bl misc_cat
    mov x21, x0
    mov x22, #1
.Lci_nx_include:
    LEA x0, tc_opts
    ldr x1, [x0, #TC_O_FLAGS]
    tst x1, #TC_F_INCL_GIVEN
    b.eq .Lci_nx_done
    mov x0, x21
    mov x1, x22
    bl misc_cat_comma_if
    mov x21, x0
    LEA x1, s_flag_include
    mov x0, x21
    bl misc_cat
    mov x21, x0
    mov x22, #1
.Lci_nx_done:
    cbz x22, .Lci_done                  // --no-exclude with nothing -> empty
