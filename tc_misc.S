// misc_names_remove(x0=name) — drop every matching entry (Python dict pop).
misc_names_remove:
    PROLOGUE 3
    mov x19, x0                         // name
    LEA x20, misc_n
    ldr x21, [x20]                      // count
    LEA x22, misc_names
    mov x23, #0                         // i
.Lnr_loop:
    cmp x23, x21
    b.ge .Lnr_out
    ldr x24, [x22, x23, lsl #3]
    mov x0, x24
    mov x1, x19
    bl strcmp
    cbz x0, .Lnr_found
    add x23, x23, #1
    b .Lnr_loop
.Lnr_found:
    // shift entries [i+1..n) left by one
    add x0, x23, #1
.Lnr_shift:
    cmp x0, x21
    b.ge .Lnr_dec
    ldr x1, [x22, x0, lsl #3]
    sub x2, x0, #1
    str x1, [x22, x2, lsl #3]
    add x0, x0, #1
    b .Lnr_shift
.Lnr_dec:
    sub x21, x21, #1
    str x21, [x20]
    // continue scanning from the same index (the next entry slid into i)
    b .Lnr_loop
.Lnr_out:
    EPILOGUE 3
    ret

// misc_sort_names(x0=array, x1=n) — insertion sort ascending (stable).
misc_sort_names:
    PROLOGUE 3
    mov x19, x0                         // array
    mov x20, x1                         // n
    cmp x20, #2
    b.lt .Lsn_out
    mov x21, #1                         // i
.Lsn_outer:
    cmp x21, x20
    b.ge .Lsn_out
    ldr x22, [x19, x21, lsl #3]         // key
    sub x23, x21, #1                    // j
.Lsn_inner:
    cmp x23, #0
    b.lt .Lsn_place
    ldr x0, [x19, x23, lsl #3]
    mov x1, x22
    bl strcmp
    cmp w0, #0
    b.le .Lsn_place
    ldr x0, [x19, x23, lsl #3]
    add x1, x23, #1
    str x0, [x19, x1, lsl #3]
    sub x23, x23, #1
    b .Lsn_inner
.Lsn_place:
    add x1, x23, #1
    str x22, [x19, x1, lsl #3]
    add x21, x21, #1
    b .Lsn_outer
.Lsn_out:
    EPILOGUE 3
    ret

