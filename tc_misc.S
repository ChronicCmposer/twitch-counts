// ============================================================================
// misc_failed(x0=msg) — "completion failed: ConfigError('<escaped msg>')\n"
//   on stderr.  Python: print(f"completion failed: {exc!r}", file=sys.stderr).
// ============================================================================
misc_failed:
    PROLOGUE 3
    // The raw message usually lives in misc_buf2 (built by the caller) and
    // the escaped copy must NOT overwrite its source, so stage the raw text
    // in misc_buf first, then escape into misc_buf2.
    mov x19, x0                         // raw message
    LEA x20, misc_buf
    mov x21, x20                        // cursor
.Lmf_copy:
    ldrb w22, [x19], #1
    strb w22, [x21], #1
    cbnz w22, .Lmf_copy
    // Python repr quote selection: single quotes preferred; a message that
    // contains a single quote but no double quote is wrapped in double quotes.
    LEA x23, misc_buf
    mov x24, #0                         // 1 = double-quote mode
    mov x19, x23
.Lmf_scan:
    ldrb w22, [x19], #1
    cbz w22, .Lmf_scan_done
    cmp w22, #'\''
    b.ne .Lmf_scan_dquote
    mov x24, #1
.Lmf_scan_dquote:
    cmp w22, #'"'
    b.ne .Lmf_scan
    // contains a double quote: force single-quote mode
    mov x24, #0
.Lmf_scan_done:
    // escape into misc_buf2
    LEA x20, misc_buf2
    mov x21, x20                        // cursor
    cbz x24, .Lmf_pre_single
    LEA x1, s_failed_prefix_dq
    b .Lmf_pre
.Lmf_pre_single:
    LEA x1, s_failed_prefix
.Lmf_pre:
    mov x0, x21
    bl misc_cat
    mov x21, x0
    LEA x23, misc_buf
    mov x19, x23                        // read pointer
.Lmf_loop:
    ldrb w22, [x19], #1
    cbz w22, .Lmf_done
    cmp w22, #'\n'
    b.eq .Lmf_nl
    cmp w22, #'\r'
    b.eq .Lmf_cr
    cmp w22, #'\t'
    b.eq .Lmf_tab
    cmp w22, #'\\'
    b.eq .Lmf_bs
    cbz x24, .Lmf_single_quote
    cmp w22, #'"'
    b.eq .Lmf_dquote
    b .Lmf_raw
.Lmf_single_quote:
    cmp w22, #'\''
    b.eq .Lmf_squote
    b .Lmf_raw
.Lmf_raw:
    strb w22, [x21], #1
    b .Lmf_loop
.Lmf_nl:
    mov w22, #'\\'
    strb w22, [x21], #1
    mov w22, #'n'
    strb w22, [x21], #1
    b .Lmf_loop
.Lmf_cr:
    mov w22, #'\\'
    strb w22, [x21], #1
    mov w22, #'r'
    strb w22, [x21], #1
    b .Lmf_loop
.Lmf_tab:
    mov w22, #'\\'
    strb w22, [x21], #1
    mov w22, #'t'
    strb w22, [x21], #1
    b .Lmf_loop
.Lmf_bs:
    mov w22, #'\\'
    strb w22, [x21], #1
    strb w22, [x21], #1
    b .Lmf_loop
.Lmf_squote:
    mov w22, #'\\'
    strb w22, [x21], #1
    mov w22, #'\''
    strb w22, [x21], #1
    b .Lmf_loop
.Lmf_dquote:
    mov w22, #'\\'
    strb w22, [x21], #1
    mov w22, #'"'
    strb w22, [x21], #1
    b .Lmf_loop
.Lmf_done:
    cbz x24, .Lmf_suf_single
    LEA x1, s_failed_suffix_dq
    b .Lmf_suf
.Lmf_suf_single:
    LEA x1, s_failed_suffix
.Lmf_suf:
    mov x0, x21
    bl misc_cat
    mov x0, x20
    bl tc_eputs
    EPILOGUE 3
    ret

