// ============================================================================
// tc_misc.S — --manual, --emit-fish-completions and --complete for
//             twitch-counts-full (Phase 8)
// ============================================================================
//
//  Target:     AArch64 (ARMv8-A), little-endian, Linux
//  Assembler:  GNU as (GAS)
//  Linking:    musl-gcc -static (musl libc + crt1.o + third_party/tomlc99/toml.o
//              + third_party/sqlite3/sqlite3.o + tc_cache.o — tc_core.o calls
//              the Phase-6 rollup-cache hooks tc_cache_day/tc_cache_put_day/
//              tc_cache_discard_day, so every binary that links tc_core.o must
//              also link tc_cache.o and sqlite3.o)
//
//  What this module owns
//  ---------------------
//    * --manual: print the module docstring with the {{ENVIRONMENT}} marker
//      replaced by environment_manual() (Python main():  print(
//      __doc__.strip().replace(ENVIRONMENT_PLACEHOLDER, environment_manual())).
//      The exact bytes live in tc_manual.inc (generated, see below).
//    * --emit-fish-completions: fish_completions(command="twitch-counts") plus
//      print()'s newline; exact bytes in tc_fish.inc.
//    * --complete KIND: run_completion() — candidates for channels, groups,
//      dates, weeks, periods, users, includes, one per line.  A failure
//      prints  completion failed: ConfigError('...')  to stderr and returns 0,
//      never a loud exit, exactly like the Python.
//
//  Exported (all .global, AAPCS64; x19-x28 preserved)
//  --------------------------------------------------
//    tc_misc_manual()          -> 0   (prints the manual to stdout)
//    tc_misc_fish()            -> 0   (prints the fish completions to stdout)
//    tc_misc_complete(x0=kind) -> 0   (TC_COMPLETE_*; prints candidates)
//    tc_misc_now_utc()         -> (x0=ymd, x1=sod)  now in UTC
//
//  Wave E wiring
//  -------------
//    main() must call tc_cli_parse(argc, argv) first (it resolves settings
//    and the window), then dispatch in the Python's order:
//        if (tc_opts.TC_O_FLAGS & TC_F_MANUAL)        return tc_misc_manual();
//        if (tc_opts.TC_O_FLAGS & TC_F_EMIT_FISH)     return tc_misc_fish();
//        if (tc_opts.TC_O_FLAGS & TC_F_COMPLETE_GIVEN)
//            return tc_misc_complete(tc_opts.TC_O_COMPLETE_KIND);
//    The .inc files are regenerated by ./gen-tc-misc-inc.sh; Wave E should
//    wire that script into the Makefile as a prerequisite of tc_misc.o so the
//    embedded text cannot drift from the Python module.
//
//  Completion pipeline (mirrors Python completion_candidates + run_completion)
//  ---------------------------------------------------------------------------
//    tc_misc_complete(kind):
//      1. config layer  (load_config_layer)  — errors print, return 0
//      2. channels/groups need no channel; the rest resolve the channel:
//         empty channel -> no output; missing logs root / channel dir ->
//         ConfigError report; dates/weeks/periods/users/includes continue
//         with the resolved channel dir (misc_cdir).
//      3. dates/weeks/periods: reuse tc_core's tc_listing (tc_count_run with
//         an all-covering window) so the FILENAME_RE filtering, date
//         validation and sort are the already-differential-tested ones.
//      4. users: 7-day counting pass via tc_count_run with a synthetic window
//         (end = now UTC, begin = end - 7d), then most_common() order, then
//         sorted(known - counts).
//      5. includes: the merged exclusion layers (Python build_exclusions)
//         computed here, so its errors stay quiet like run_completion.
//
//  Deviation notes (documented for later phases)
//  ---------------------------------------------
//    * misc_complete_users uses UTC "now" (the Python uses local time); the
//      differential generates logs that cover any 7-day window.
//    * Config TOML errors use tomlc99's message ("line N: ...") instead of
//      tomllib's; the "could not read config <path>: " prefix is identical.
//    * The completion module re-parses the config with tomlc99 directly
//      instead of going through tc_config.S, so a broken config cannot exit 1
//      at a prompt (run_completion catches and reports on stderr).
//    * Environment lookups use libc getenv() directly (never tc_env_get, which
//      would load the config and could tc_fail on a broken file).
// ============================================================================

