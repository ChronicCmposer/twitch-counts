misc_arena_reset:
    LEA x0, misc_cur
    str xzr, [x0]
    ret

// misc_alloc(x0=size) -> x0 = 8-aligned arena pointer.
misc_alloc:
    PROLOGUE 0
    add x0, x0, #7
    and x0, x0, #~7
    mov x1, x0                          // rounded size
    LEA x2, misc_cur
    ldr x3, [x2]
    cbnz x3, .Lal_have_base
    LEA x3, misc_arena
    str x3, [x2]
.Lal_have_base:
    mov x0, x3                          // result
    add x3, x3, x1
    LEA_OFF x2, misc_arena, MISC_ARENA_SZ
    cmp x3, x2
    b.ls .Lal_ok
    LEA x0, s_arena_exhausted
    bl tc_fail
.Lal_ok:
    LEA x2, misc_cur
    str x3, [x2]
    EPILOGUE 0
    ret

// misc_arena_str(x0=src) -> x0 = NUL-terminated arena copy.
misc_arena_str:
    PROLOGUE 2
    mov x19, x0                         // src
    bl tc_strlen
    add x0, x0, #1
    bl misc_alloc                       // x0 = dst base
    mov x20, x0                         // cursor
    mov x21, x0                         // base
.Las_copy:
    ldrb w1, [x19], #1
    strb w1, [x20], #1
    cbnz w1, .Las_copy
    mov x0, x21
    EPILOGUE 2
    ret

// misc_arena_str_lower_strip(x0=src) -> x0 = arena copy of the lowercased,
//   whitespace-stripped string, or 0 when the result would be empty
//   (Python cfg_split_names: str(item).strip().lower(), drop empties).
misc_arena_str_lower_strip:
    PROLOGUE 2
    mov x19, x0                         // scan pointer
.Lasls_lead:
    ldrb w1, [x19]
    cmp w1, #' '
    b.eq .Lasls_lead_skip
    cmp w1, #'\t'
    b.eq .Lasls_lead_skip
    cbz w1, .Lasls_empty
    b .Lasls_find_end
.Lasls_lead_skip:
    add x19, x19, #1
    b .Lasls_lead
.Lasls_find_end:
    mov x20, x19                        // start
    mov x21, x19                        // end (last non-ws byte)
.Lasls_scan:
    ldrb w1, [x19], #1
    cbz w1, .Lasls_scan_done
    cmp w1, #' '
    b.eq .Lasls_scan
    cmp w1, #'\t'
    b.eq .Lasls_scan
    sub x21, x19, #1
    b .Lasls_scan
.Lasls_scan_done:
    sub x22, x21, x20                   // len = end - start
    add x22, x22, #1
    add x0, x22, #1
    bl misc_alloc                       // x0 = dst base
    mov x19, x0                         // cursor
    mov x1, x22                         // len
    mov x2, x20                         // src
.Lasls_copy:
    cbz x1, .Lasls_nul
    ldrb w3, [x2], #1
    cmp w3, #'A'
    b.lt .Lasls_store
    cmp w3, #'Z'
    b.gt .Lasls_store
    add w3, w3, #('a' - 'A')
.Lasls_store:
    strb w3, [x19], #1
    sub x1, x1, #1
    b .Lasls_copy
.Lasls_nul:
    mov w3, #0
    strb w3, [x19]
    sub x0, x19, x22                    // dst base
    EPILOGUE 2
    ret
.Lasls_empty:
    mov x0, #0
    EPILOGUE 2
    ret

